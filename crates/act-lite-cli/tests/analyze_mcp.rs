#[test]
fn mcp_result_equals_cli_stdout() {
    let conv_ws = TempDir::new().unwrap();
    conv(conv_ws.path());
    let toml_ws = TempDir::new().unwrap();
    write(toml_ws.path(), "Cargo.toml", "[package]\nname = \"c\"\n");
    write(toml_ws.path(), "src/ok.rs", "fn ok() {}\n");
    let many_ws = TempDir::new().unwrap();
    many_tests(many_ws.path());

    let cases: [(&[&str], Value); 7] = [
        (&["--limit", "2"], json!({"limit": 2})),
        (&["--limit", "1000"], json!({"limit": 1000})),
        (&["--limit", "0"], json!({"limit": 0})),
        (&["Cargo.toml"], json!({"paths": ["Cargo.toml"]})),
        (&[], json!({})),
        (&["--include-tests"], json!({"include_tests": true})),
        (
            &["src", "--include", "*.rs", "--exclude", "src/lib.rs"],
            json!({"paths": ["src"], "include": ["*.rs"], "exclude": ["src/lib.rs"]}),
        ),
    ];
    for analyzer in ANALYZERS {
        let mut session = Session::start(conv_ws.path());
        for (args, params) in &cases {
            assert_eq!(
                session.ok_of(analyzer, params.clone()).0,
                cli_of(conv_ws.path(), analyzer, args),
                "{analyzer} {params}"
            );
        }
        for ws in [&toml_ws, &many_ws] {
            assert_eq!(
                Session::start(ws.path()).ok_of(analyzer, json!({})).0,
                cli_of(ws.path(), analyzer, &[]),
                "{analyzer}"
            );
        }
    }
}

