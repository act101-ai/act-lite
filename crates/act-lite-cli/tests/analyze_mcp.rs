/// `src/t.rs`: one function at and one over each threshold of `patterns`;
/// four findings.
fn thresholds_rs() -> String {
    let long_function = |signature: &str, lets: usize| {
        let mut out = format!("{signature} {{\n");
        out.push_str(&"    // note\n".repeat(6));
        out.push_str(&"\n".repeat(4));
        for i in 0..lets {
            out.push_str(&format!("    let v{i} = {i};\n"));
        }
        out.push_str("}\n");
        out
    };
    let mut src = long_function("fn lines_at()", 48);
    src.push('\n');
    src.push_str(&long_function("fn lines_over()", 49));
    src.push_str(
        "
fn nest_at(x: u8) {
    if x > 0 {
        for _i in 0..x {
            while x > 1 {
                match x {
                    _ => {}
                }
            }
        }
    }
}

fn nest_over(x: u8) {
    if x > 0 {
        for _i in 0..x {
            while x > 1 {
                match x {
                    _ => loop {
                        break;
                    },
                }
            }
        }
    }
}

",
    );
    src.push_str("fn cc_at(x: u8) {\n");
    src.push_str(&"    if x == 1 {}\n".repeat(9));
    src.push_str("}\n\nfn cc_over(x: u8) {\n");
    src.push_str(&"    if x == 1 {}\n".repeat(10));
    src.push_str(
        "}

struct S;
impl S {
    fn p_at(&self, a: u8, b: u8, c: u8, d: u8, e: u8) {}
}

fn p_over(a: u8, b: u8, c: u8, d: u8, e: u8, f: u8) {}
",
    );
    src
}

/// `src/a.rs` (functions `f` and `g`) and `src/b.rs` (one function of 20
/// lines): two ranked files.
fn ranking_workspace(root: &Path) {
    write(
        root,
        "src/a.rs",
        "fn f(x: u8) -> u8 {\n    if x > 1 {\n        return 1;\n    }\n    if x > 2 {\n        return 2;\n    }\n    0\n    + 0\n}\nfn g() {\n    let _ = 1;\n}\n",
    );
    let mut b = String::from("fn h(x: u8) -> u8 {\n");
    for i in 1..=4 {
        b.push_str(&format!("    if x > {i} {{ return {i}; }}\n"));
    }
    for i in 0..13 {
        b.push_str(&format!("    let _v{i} = {i};\n"));
    }
    b.push_str("    0\n}\n");
    write(root, "src/b.rs", &b);
}

