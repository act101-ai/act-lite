#[test]
fn mcp_result_equals_cli_stdout() {
    let ws = TempDir::new().unwrap();
    conv(ws.path());
    let mut session = Session::start(ws.path());
    let cases: [(&[&str], Value); 7] = [
        (&["--limit", "2"], json!({"limit": 2})),
        (&["--limit", "1000"], json!({"limit": 1000})),
        (&["--limit", "0"], json!({"limit": 0})),
        (&["Cargo.toml"], json!({"paths": ["Cargo.toml"]})),
        (&[], json!({})),
        (&["--include-tests"], json!({"include_tests": true})),
        (
            &["src", "--include", "*.rs", "--exclude", "src/lib.rs"],
            json!({"paths": ["src"], "include": ["*.rs"], "exclude": ["src/lib.rs"]}),
        ),
    ];
    for (args, params) in cases {
        assert_eq!(
            session.ok(params.clone()).0,
            cli(ws.path(), args),
            "{params}"
        );
    }

    let ws = TempDir::new().unwrap();
    write(ws.path(), "Cargo.toml", "[package]\nname = \"c\"\n");
    write(ws.path(), "src/ok.rs", "fn ok() {}\n");
    assert_eq!(
        Session::start(ws.path()).ok(json!({})).0,
        cli(ws.path(), &[])
    );

    let ws = TempDir::new().unwrap();
    many_tests(ws.path());
    assert_eq!(
        Session::start(ws.path()).ok(json!({})).0,
        cli(ws.path(), &[])
    );
}

