//! End-to-end tests of the `analyze_*` MCP tools, run against the built
//! `act-lite mcp serve` over stdio. The shared conventions run with
//! `analyze_patterns`, which reports a function with more than 5 parameters,
//! and the checks that every analyzer must pass run with each of
//! `analyze_patterns`, `analyze_hotspots` and `analyze_clones`. Every
//! workspace is synthetic and built in a temporary directory; expected values
//! come from the fixture sources and the documented rules, not from the
//! binary's output.
#![cfg(unix)]

use serde_json::{Value, json};
use std::fs;
use std::io::{BufRead, BufReader, Write};
use std::path::Path;
use std::process::{Child, ChildStdin, Command, Stdio};
use std::sync::mpsc::{Receiver, channel};
use std::time::{Duration, Instant};
use tempfile::TempDir;

const SIZE_CAP: usize = 8 * 1024 * 1024;

fn write(root: &Path, rel: &str, content: &str) {
    let path = root.join(rel);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

/// An 8-line function with 6 parameters: `patterns` reports it, as one
/// `long_parameter_list` finding and no other.
fn reported_fn(name: &str) -> String {
    format!(
        "fn {name}(p1: u8, p2: u8, p3: u8,\n     p4: u8, p5: u8, p6: u8) -> u8 {{\n    let s = p1 + p2;\n    let t = p3 + p4;\n    let u = p5 + p6;\n    s + t\n        + u\n}}\n"
    )
}

const ANALYZERS: [&str; 3] = ["patterns", "hotspots", "clones"];

const TEST_MOD: &str = "\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn t() {}\n}\n";

/// The `conv` workspace: three reported functions, one test region, one test
/// file, and one file each for the generated, vendored, ignored and oversize
/// cases. `src/broken.rs` has a syntax error inside its function body.
fn conv(root: &Path) {
    fs::create_dir_all(root.join(".git")).unwrap();
    write(root, ".gitignore", "build-out/\n*.log\n");
    write(root, "Cargo.toml", "[package]\nname = \"conv\"\n");
    write(
        root,
        "src/lib.rs",
        &format!("{}{TEST_MOD}", reported_fn("a")),
    );
    write(
        root,
        "src/big.rs",
        &format!("//{}\n", "x".repeat(SIZE_CAP - 2)),
    );
    write(
        root,
        "src/broken.rs",
        "fn b(p1: u8, p2: u8, p3: u8,\n     p4: u8, p5: u8, p6: u8) -> u8 {\n    let a = p1;\n    let c = ;\n    a\n}\n",
    );
    write(root, "src/more.rs", &reported_fn("a"));
    write(
        root,
        "src/gen.rs",
        &format!(
            "// Code generated by synth. DO NOT EDIT.\n{}",
            reported_fn("g")
        ),
    );
    write(root, "src/notes.txt", "notes");
    write(root, "tests/cli.rs", "fn t() {}");
    write(root, "vendor/dep/lib.rs", "fn v() {}");
    write(root, "build-out/x.rs", "fn x() {}");
    write(root, "debug.log", "log");
}

/// A workspace with `src/ok.rs`, which `patterns` does not report, and 101
/// test files.
fn many_tests(root: &Path) {
    write(root, "src/ok.rs", "fn ok() {}\n");
    for i in 0..101 {
        write(root, &format!("tests/t{i:03}.rs"), "fn t() {}\n");
    }
}

/// A running `act-lite --workspace <ws> mcp serve` and the lines it has sent.
struct Session {
    child: Child,
    stdin: ChildStdin,
    replies: Receiver<String>,
    next_id: u64,
}

impl Drop for Session {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

impl Session {
    /// Starts the server with language servers disabled.
    fn start(ws: &Path) -> Session {
        Self::start_with(ws, &["--disable-lsp"], None)
    }

    /// Starts the server with `flags` before the subcommand and, when given,
    /// `path` as `PATH`, and performs the `initialize` handshake.
    fn start_with(ws: &Path, flags: &[&str], path: Option<&Path>) -> Session {
        let config = TempDir::new().unwrap();
        let mut cmd = Command::new(env!("CARGO_BIN_EXE_act-lite"));
        cmd.env("ACT_CONFIG_DIR", config.path())
            .env_remove("ACT_LITE_DISABLE_LSP")
            .args(flags)
            .arg("--workspace")
            .arg(ws)
            .args(["mcp", "serve"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null());
        if let Some(path) = path {
            cmd.env("PATH", path);
        }
        let mut child = cmd.spawn().expect("the act-lite binary must start");
        let stdin = child.stdin.take().unwrap();
        let stdout = child.stdout.take().unwrap();
        let (tx, replies) = channel();
        std::thread::spawn(move || {
            for line in BufReader::new(stdout).lines() {
                let Ok(line) = line else { break };
                if tx.send(line).is_err() {
                    break;
                }
            }
        });
        let mut session = Session {
            child,
            stdin,
            replies,
            next_id: 1,
        };
        session.request(
            "initialize",
            json!({"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"test","version":"0"}}),
        );
        session.send(&json!({"jsonrpc":"2.0","method":"notifications/initialized"}));
        session
    }

    fn send(&mut self, message: &Value) {
        writeln!(self.stdin, "{message}").unwrap();
        self.stdin.flush().unwrap();
    }

    /// Sends a request without waiting; returns its id.
    fn send_request(&mut self, method: &str, params: Value) -> u64 {
        let id = self.next_id;
        self.next_id += 1;
        self.send(&json!({"jsonrpc":"2.0","id":id,"method":method,"params":params}));
        id
    }

    /// Reads replies until the one for `id`; returns it and the ids of the
    /// replies before it.
    fn wait_for(&mut self, id: u64, timeout: Duration) -> (Value, Vec<Value>) {
        let mut before = Vec::new();
        let deadline = Instant::now() + timeout;
        loop {
            let left = deadline.saturating_duration_since(Instant::now());
            let line = self
                .replies
                .recv_timeout(left)
                .unwrap_or_else(|e| panic!("no reply for id {id}: {e}"));
            if let Ok(v) = serde_json::from_str::<Value>(&line) {
                if v["id"] == id {
                    return (v, before);
                }
                before.push(v["id"].clone());
            }
        }
    }

    fn request(&mut self, method: &str, params: Value) -> Value {
        let id = self.send_request(method, params);
        self.wait_for(id, Duration::from_secs(120)).0
    }

    /// `tools/call` of the tool `name`.
    fn call_tool(&mut self, name: &str, arguments: Value) -> Value {
        self.request("tools/call", json!({"name": name, "arguments": arguments}))
    }

    /// `tools/call` of `analyze_<analyzer>`.
    fn call(&mut self, analyzer: &str, arguments: Value) -> Value {
        self.call_tool(&format!("analyze_{analyzer}"), arguments)
    }

    /// A `patterns` call that must succeed: its two text blocks, the first
    /// parsed as JSON.
    fn ok(&mut self, arguments: Value) -> (Value, String) {
        self.ok_of("patterns", arguments)
    }

    /// A call that must succeed: its two text blocks, the first parsed as JSON.
    fn ok_of(&mut self, analyzer: &str, arguments: Value) -> (Value, String) {
        let reply = self.call(analyzer, arguments.clone());
        assert!(
            reply.get("error").is_none() && reply["result"]["isError"] != true,
            "{arguments} must succeed: {reply}"
        );
        let content = reply["result"]["content"].as_array().unwrap();
        assert_eq!(content.len(), 2, "{reply}");
        let text = content[0]["text"].as_str().unwrap();
        assert!(!text.contains("Note:"), "{text}");
        let json = serde_json::from_str(text).unwrap_or_else(|e| panic!("not JSON ({e}): {text}"));
        (json, content[1]["text"].as_str().unwrap().to_string())
    }

    /// A call that must fail with a JSON-RPC error; returns its code and message.
    fn err(&mut self, arguments: Value) -> (i64, String) {
        let reply = self.call("patterns", arguments.clone());
        let error = &reply["error"];
        assert!(error.is_object(), "{arguments} must fail: {reply}");
        (
            error["code"].as_i64().unwrap(),
            error["message"].as_str().unwrap().to_string(),
        )
    }
}

/// The parsed stdout of `act-lite --workspace <ws> analyze <analyzer> <args>`.
fn cli_of(ws: &Path, analyzer: &str, args: &[&str]) -> Value {
    let config = TempDir::new().unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_act-lite"))
        .env("ACT_CONFIG_DIR", config.path())
        .env_remove("ACT_LITE_DISABLE_LSP")
        .arg("--disable-lsp")
        .arg("--workspace")
        .arg(ws)
        .args(["analyze", analyzer])
        .args(args)
        .output()
        .unwrap();
    assert_eq!(
        out.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    serde_json::from_slice(&out.stdout).expect("stdout is one JSON value")
}

/// The stderr message of a CLI request error of `analyze <analyzer>`.
fn cli_error_of(ws: &Path, analyzer: &str, args: &[&str]) -> String {
    let config = TempDir::new().unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_act-lite"))
        .env("ACT_CONFIG_DIR", config.path())
        .arg("--workspace")
        .arg(ws)
        .args(["analyze", analyzer])
        .args(args)
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(1));
    let v: Value = serde_json::from_slice(&out.stderr).unwrap();
    v["error"]["message"].as_str().unwrap().to_string()
}

