type Snapshot = BTreeMap<String, (Vec<u8>, SystemTime)>;

fn snapshot(root: &Path) -> Snapshot {
    fn walk(root: &Path, dir: &Path, out: &mut Snapshot) {
        for entry in fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            let meta = fs::symlink_metadata(&path).unwrap();
            let rel = path.strip_prefix(root).unwrap().display().to_string();
            let content = if meta.is_file() {
                fs::read(&path).unwrap()
            } else {
                Vec::new()
            };
            out.insert(rel, (content, meta.modified().unwrap()));
            if meta.is_dir() {
                walk(root, &path, out);
            }
        }
    }
    let mut out = Snapshot::new();
    walk(root, root, &mut out);
    out
}

fn group_members(pgid: u32) -> String {
    let out = std::process::Command::new("pgrep")
        .args(["-g", &pgid.to_string()])
        .output()
        .unwrap();
    String::from_utf8(out.stdout).unwrap()
}

#[test]
fn writes_no_artifacts_and_leaves_no_process() {
    let ws = TempDir::new().unwrap();
    conv(ws.path());
    let config = TempDir::new().unwrap();
    let before = (snapshot(ws.path()), snapshot(config.path()));
    for args in [
        &[][..],
        &["--include-tests", "--include-vendored"],
        &["tests"],
    ] {
        let mut cmd = std::process::Command::new(env!("CARGO_BIN_EXE_act-lite"));
        cmd.env("ACT_CONFIG_DIR", config.path())
            .arg("--workspace")
            .arg(ws.path())
            .args(["analyze", "fixture"])
            .args(args)
            .process_group(0)
            .stdout(Stdio::null())
            .stderr(Stdio::null());
        let child = cmd.spawn().unwrap();
        let pgid = child.id();
        child.wait_with_output().unwrap();
        assert_eq!(
            group_members(pgid).trim(),
            "",
            "a process remains in the group"
        );
    }
    assert!(before.0 == snapshot(ws.path()), "the workspace changed");
    assert!(
        before.1 == snapshot(config.path()),
        "the configuration directory changed"
    );
}

#[test]
fn file_symlinks() {
    let root = TempDir::new().unwrap();
    let ws = root.path().join("ws");
    let outside = root.path().join("outside");
    write(&outside, "t.rs", &long_fn("t"));
    write(&ws, "src/ok.rs", &short_fn("ok"));
    write(&ws, "real.rs", &long_fn("r"));
    write(&ws, "sub/inner.rs", &long_fn("i"));
    symlink(outside.join("t.rs"), ws.join("src/out.rs")).unwrap();
    symlink(outside.join("t.rs"), ws.join("src/out.toml")).unwrap();
    symlink(ws.join("real.rs"), ws.join("src/alias.rs")).unwrap();
    symlink(ws.join("sub"), ws.join("dirlink")).unwrap();
    let v = run(&ws, &[]).json();
    let skipped = v["incomplete"]["skipped_files"].as_array().unwrap();
    assert_eq!(skipped.len(), 1);
    assert_eq!(skipped[0]["file"], "src/out.rs");
    assert_eq!(skipped[0]["kind"], "symlink_outside_workspace");
    assert_eq!(files_of(&v), ["real.rs", "sub/inner.rs"]);
    let text = v.to_string();
    for name in ["out.toml", "alias.rs", "dirlink"] {
        assert!(!text.contains(name), "{name} must not appear");
    }
}

