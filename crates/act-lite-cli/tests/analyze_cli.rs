#[test]
fn ordering_is_by_path_bytes_and_stable() {
    let ws = TempDir::new().unwrap();
    write(ws.path(), "a-b/x.rs", &reported_fn("f"));
    write(ws.path(), "a/b.rs", &reported_fn("f"));
    for analyzer in ["patterns", "hotspots"] {
        let first = run_named(ws.path(), analyzer, &[]);
        assert_eq!(
            files_of(&first.json()),
            ["a-b/x.rs", "a/b.rs"],
            "{analyzer}"
        );
        assert_eq!(
            first.stdout,
            run_named(ws.path(), analyzer, &[]).stdout,
            "{analyzer}"
        );
    }
    let first = run_named(ws.path(), "clones", &[]);
    let v = first.json();
    assert_eq!(v["total"], 1, "{v}");
    let members: Vec<&str> = v["findings"][0]["members"]
        .as_array()
        .unwrap()
        .iter()
        .map(|m| m["file"].as_str().unwrap())
        .collect();
    assert_eq!(members, ["a-b/x.rs", "a/b.rs"]);
    assert_eq!(first.stdout, run_named(ws.path(), "clones", &[]).stdout);
}

