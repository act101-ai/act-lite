//! End-to-end tests of `act-lite analyze`, run against the built binary.
//! The shared conventions run with `patterns`, which reports a function with
//! more than 5 parameters, and the checks that every analyzer must pass run
//! with each of `patterns`, `hotspots` and `clones`. Every workspace is
//! synthetic and built in a temporary directory; expected values come from
//! the fixture sources and the documented rules, not from the binary's
//! output.
#![cfg(unix)]

use assert_cmd::Command;
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::fs;
use std::os::unix::fs::symlink;
use std::os::unix::process::{CommandExt, ExitStatusExt};
use std::path::Path;
use std::process::Stdio;
use std::time::SystemTime;
use tempfile::TempDir;

const SIZE_CAP: usize = 8 * 1024 * 1024;

fn write(root: &Path, rel: &str, content: &str) {
    let path = root.join(rel);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

/// An 8-line function with 6 parameters: `patterns` reports it, as one
/// `long_parameter_list` finding and no other.
fn reported_fn(name: &str) -> String {
    format!(
        "fn {name}(p1: u8, p2: u8, p3: u8,\n     p4: u8, p5: u8, p6: u8) -> u8 {{\n    let s = p1 + p2;\n    let t = p3 + p4;\n    let u = p5 + p6;\n    s + t\n        + u\n}}\n"
    )
}

/// The shape of `reported_fn` with 5 parameters: `patterns` does not report it.
fn quiet_fn(name: &str) -> String {
    format!(
        "fn {name}(p1: u8, p2: u8, p3: u8,\n     p4: u8, p5: u8) -> u8 {{\n    let s = p1 + p2;\n    let t = p3 + p4;\n    let u = p5;\n    s + t\n        + u\n}}\n"
    )
}

/// A function that `patterns` does not report.
fn short_fn(name: &str) -> String {
    format!("fn {name}() {{\n    let x = 1;\n}}\n")
}

const ANALYZERS: [&str; 3] = ["patterns", "hotspots", "clones"];

const TEST_MOD: &str = "\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn t() {}\n}\n";

/// The `conv` workspace: three reported functions, one test region, one test
/// file, and one file each for the generated, vendored, ignored and oversize
/// cases. `src/broken.rs` has a syntax error inside its function body.
fn conv(root: &Path) {
    fs::create_dir_all(root.join(".git")).unwrap();
    write(root, ".gitignore", "build-out/\n*.log\n");
    write(root, "Cargo.toml", "[package]\nname = \"conv\"\n");
    write(
        root,
        "src/lib.rs",
        &format!("{}{TEST_MOD}", reported_fn("a")),
    );
    let big = format!("//{}\n", "x".repeat(SIZE_CAP + 1 - 3));
    assert_eq!(big.len(), SIZE_CAP + 1);
    write(root, "src/big.rs", &big);
    write(
        root,
        "src/broken.rs",
        "fn b(p1: u8, p2: u8, p3: u8,\n     p4: u8, p5: u8, p6: u8) -> u8 {\n    let a = p1;\n    let c = ;\n    a\n}\n",
    );
    write(root, "src/more.rs", &reported_fn("a"));
    write(
        root,
        "src/gen.rs",
        &format!(
            "// Code generated by synth. DO NOT EDIT.\n{}",
            reported_fn("g")
        ),
    );
    write(root, "src/notes.txt", "notes");
    write(root, "tests/cli.rs", "fn t() {}");
    write(root, "vendor/dep/lib.rs", "fn v() {}");
    write(root, "build-out/x.rs", "fn x() {}");
    write(root, "debug.log", "log");
}

struct Run {
    code: Option<i32>,
    stdout: String,
    stderr: String,
}

impl Run {
    fn json(&self) -> Value {
        assert_eq!(self.code, Some(0), "stderr: {}", self.stderr);
        serde_json::from_str(&self.stdout).expect("stdout is one JSON value")
    }
}

fn base(ws: &Path, config: &Path, analyzer: &str) -> Command {
    let mut cmd = Command::cargo_bin("act-lite").expect("the act-lite binary must be built");
    cmd.env("ACT_CONFIG_DIR", config)
        .env_remove("ACT_LITE_DISABLE_LSP")
        .arg("--workspace")
        .arg(ws)
        .args(["analyze", analyzer]);
    cmd
}

fn finish(mut cmd: Command) -> Run {
    let out = cmd.output().unwrap();
    Run {
        code: out.status.code(),
        stdout: String::from_utf8(out.stdout).unwrap(),
        stderr: String::from_utf8(out.stderr).unwrap(),
    }
}

/// `act-lite --workspace <ws> analyze <analyzer> <args>`.
fn run_named(ws: &Path, analyzer: &str, args: &[&str]) -> Run {
    let config = TempDir::new().unwrap();
    let mut cmd = base(ws, config.path(), analyzer);
    cmd.args(args);
    finish(cmd)
}

fn run(ws: &Path, args: &[&str]) -> Run {
    run_named(ws, "patterns", args)
}

fn files_of(v: &Value) -> Vec<String> {
    v["findings"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["file"].as_str().unwrap().to_string())
        .collect()
}

fn paths_of(v: &Value, category: &str) -> Vec<String> {
    v["excluded"][category]
        .as_array()
        .unwrap()
        .iter()
        .map(|e| e["path"].as_str().unwrap().to_string())
        .collect()
}

fn empty_scope(tests: u32, generated: u32, vendored: u32, ignored: u32) -> String {
    format!(
        "no files to analyze in the requested scope: {tests} excluded as tests, {generated} as generated, {vendored} as vendored, {ignored} as ignored; 0 left out by include or exclude; 0 unrecognized. Re-run with the matching include option (tests, generated, vendored, ignored)."
    )
}

fn frame(message: &str) -> String {
    format!("{}\n", json!({"error": {"message": message, "chain": []}}))
}

fn ok_only(root: &Path) {
    write(root, "src/ok.rs", &short_fn("ok"));
}

#[test]
fn shape_has_every_key() {
    let ws = TempDir::new().unwrap();
    conv(ws.path());
    for analyzer in ANALYZERS {
        shape_of(&run_named(ws.path(), analyzer, &[]).json(), analyzer);
    }
}

fn shape_of(v: &Value, analyzer: &str) {
    let keys = |v: &Value| -> Vec<String> { v.as_object().unwrap().keys().cloned().collect() };
    let mut top = keys(v);
    top.sort();
    let mut want: Vec<String> = [
        "analysis",
        "status",
        "complete",
        "findings",
        "total",
        "limit",
        "truncated",
        "coverage",
        "excluded",
        "incomplete",
        "evidence",
        "details",
    ]
    .map(String::from)
    .to_vec();
    want.sort();
    assert_eq!(top, want);
    assert_eq!(v["analysis"], analyzer);
    let mut k = keys(&v["coverage"]);
    k.sort();
    assert_eq!(k, ["analyzed_files", "languages", "unrecognized_files"]);
    let mut k = keys(&v["excluded"]);
    k.sort();
    assert_eq!(
        k,
        [
            "counts",
            "generated",
            "ignored",
            "tests",
            "truncated",
            "vendored"
        ]
    );
    let mut k = keys(&v["incomplete"]);
    k.sort();
    assert_eq!(
        k,
        [
            "counts",
            "limits_hit",
            "parse_failures",
            "skipped_files",
            "truncated",
            "unresolved"
        ]
    );
    let mut k = keys(&v["evidence"]);
    k.sort();
    assert_eq!(k, ["language_servers", "sources"]);
}

