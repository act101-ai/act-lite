#[test]
fn cancellation_by_sigint() {
    // Local only: it needs a workspace that takes over a second to analyze.
    if std::env::var("ACT_LITE_CHECK_PERF").as_deref() != Ok("1") {
        eprintln!("skipped: ACT_LITE_CHECK_PERF not set");
        return;
    }
    let ws = TempDir::new().unwrap();
    for i in 0..SLOW_FILES {
        write(
            ws.path(),
            &format!("d{:03}/f{i}.rs", i % 200),
            &long_fn("f"),
        );
    }
    let config = TempDir::new().unwrap();
    let start = std::time::Instant::now();
    assert_eq!(finish(base(ws.path(), config.path())).code, Some(0));
    assert!(
        start.elapsed().as_secs_f64() > 1.0,
        "the workspace is too small: {:?}",
        start.elapsed()
    );

    let mut cmd = std::process::Command::new(env!("CARGO_BIN_EXE_act-lite"));
    cmd.env("ACT_CONFIG_DIR", config.path())
        .arg("--workspace")
        .arg(ws.path())
        .args(["analyze", "fixture"])
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    let child = cmd.spawn().unwrap();
    std::thread::sleep(std::time::Duration::from_millis(100));
    let sent = std::process::Command::new("kill")
        .args(["-INT", &child.id().to_string()])
        .status()
        .unwrap();
    assert!(sent.success());
    let out = child.wait_with_output().unwrap();
    assert_eq!(out.status.signal(), Some(2));
    assert!(out.stdout.is_empty());
}

const SLOW_FILES: usize = 30_000;
